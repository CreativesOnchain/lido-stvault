// Helper Formatters
// -----------------------------------------------------------------------------

/// Formats validator public key and optional index safely without out-of-bounds panics.
fn format_validator_display(pubkey: &str, index: Option<u64>) -> String {
    let prefix_len = pubkey.len().min(10);
    let short_key = &pubkey[..prefix_len];

    match index {
        Some(idx) => format!("Index `{}` (`{}...`)", idx, short_key),
        None => format!("`{}...`", short_key),
    }
}

/// Formats a transaction hash into a shortened 0x1234...5678 format safely.
fn format_tx_hash_short(tx_hash: Option<&str>) -> String {
    match tx_hash {
        Some(h) if h.len() > 14 => format!("`{}...{}`", &h[..8], &h[h.len() - 6..]),
        Some(h) => format!("`{}`", h),
        None => "N/A".to_string(),
    }
}

/// Returns a Markdown badge for a given consolidation status.
fn status_badge_markdown(status: ConsolidationStatus) -> &'static str {
    match status {
        ConsolidationStatus::Accepted => "✅ **ACCEPTED**",
        ConsolidationStatus::Queued => "⏳ **QUEUED**",
        ConsolidationStatus::NotAccepted => "❌ **NOT_ACCEPTED**",
        ConsolidationStatus::Indeterminate => "❓ **INDETERMINATE**",
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::models::{LidoFeeExemptionReport, VerificationSummary};
    use chrono::Utc;

    #[test]
    fn test_generate_markdown_receipt() {
        let receipt = VerificationReceipt {
            tool_version: "0.1.0".to_string(),
            timestamp: Utc::now(),
            el_rpc_url: "http://localhost:8545".to_string(),
            cl_beacon_url: "http://localhost:5052".to_string(),
            summary: VerificationSummary {
                total_pairs: 1,
                accepted: 1,
                ..Default::default()
            },
            fee_exemption: LidoFeeExemptionReport {
                st_vault_dashboard: None,
                operator_address: None,
                role_hash: "0x123".to_string(),
                role_active: Some(false),
                fee_exemption_observed: true,
                notes: "Clean".to_string(),
            },
            pairs: vec![PairVerificationResult {
                source_pubkey: "0x0102030405060708090a".to_string(),
                source_index: Some(123),
                target_pubkey: "0x0a090807060504030201".to_string(),
                target_index: Some(456),
                el_tx_hash: Some("0x11223344556677889900aabbccddeeff".to_string()),
                el_block_number: Some(100),
                el_predeploy_found: true,
                beacon_slot: Some(200),
                beacon_request_found: true,
                cl_pending_found: true,
                status: ConsolidationStatus::Accepted,
                details: "Verified in queue".to_string(),
                indeterminate_reason: None,
            }],
        };

        let md = generate_markdown_receipt(&receipt);
        assert!(md.contains("# Lido stVault Consolidation Request Receipt"));
        assert!(md.contains("**STATUS: ALL CONSOLIDATION REQUESTS ACCEPTED**"));
        assert!(md.contains("Index `123` (`0x01020304...`)"));
        assert!(md.contains("✅ **ACCEPTED**"));
    }
}
